_current_lang = "ro"


def set_language(lang: str):
    global _current_lang
    if lang in TRANSLATIONS:
        _current_lang = lang


def get_language() -> str:
    return _current_lang


def t(key: str) -> str:
    """Return translated string for key in current language, with Romanian fallback."""
    lang_dict = TRANSLATIONS.get(_current_lang, TRANSLATIONS["ro"])
    result = lang_dict.get(key)
    if result is None:
        result = TRANSLATIONS["ro"].get(key, key)
    return result


